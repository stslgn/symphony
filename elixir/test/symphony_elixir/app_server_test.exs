      System.put_env("PATH", test_root <> ":" <> (previous_path || ""))

      Enum.each(secret_env_names, fn name ->
        System.put_env(name, "test-only-#{String.downcase(name)}")
      end)

      env_probe =
        Enum.map_join(secret_env_names, "\n", fn name ->
          "printf 'ENV:#{name}=%s\\n' \"${#{name}-__ABSENT__}\" >> \"$trace_file\""
        end)

      File.write!(fake_ssh, """
      #!/bin/sh
      trace_file="${SYMP_TEST_SSH_TRACE:-/tmp/symphony-fake-ssh.trace}"
      count=0
      printf 'ARGV:%s\\n' "$*" >> "$trace_file"
      #{env_probe}

      while IFS= read -r line; do
        count=$((count + 1))
        printf 'JSON:%s\\n' "$line" >> "$trace_file"

        case "$count" in
          1)
            printf '%s\\n' '{"id":1,"result":{}}'
            ;;
          2)
            printf '%s\\n' '{"id":2,"result":{"thread":{"id":"thread-remote"}}}'
            ;;
          3)
            printf '%s\\n' '{"id":3,"result":{"turn":{"id":"turn-remote"}}}'
            ;;
          4)
            printf '%s\\n' '{"method":"turn/completed"}'
            exit 0
            ;;
          *)
            exit 0
            ;;
        esac
      done
      """)

